#!/usr/bin/env bash
# Regenerates THIRD-PARTY-NOTICES.txt, the license notices of everything
# third-party compiled or embedded into the apb binary:
#   1. Rust crates, from Cargo.lock via cargo-about (about.toml, about.hbs),
#      limited to the shipped release targets and the apb package's graph.
#   2. npm packages that the production Vite build puts into web/dist, from
#      web/bun.lock via web/scripts/third-party-notices.ts.
#
# Usage (from anywhere in the repository):
#   scripts/third-party-notices.sh          rewrite THIRD-PARTY-NOTICES.txt
#   scripts/third-party-notices.sh --check  exit 1 when the committed file is stale
#
# Requires cargo-about (the version pinned in scripts/install-cargo-about.sh) and
# bun. cargo-about runs with --frozen: no network, license texts come from the
# crate sources in the local cargo registry, so the output depends only on the
# lockfiles.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
out="$root/THIRD-PARTY-NOTICES.txt"
mode="${1:-write}"
case "$mode" in
  write | --check) ;;
  *)
    echo "usage: $0 [--check]" >&2
    exit 2
    ;;
esac

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

cd "$root"
cargo fetch --locked --quiet
cargo about generate --frozen \
  --manifest-path crates/apb-cli/Cargo.toml \
  --config about.toml \
  --output-file "$work/rust.txt" \
  about.hbs 2>"$work/cargo-about.log" || {
  cat "$work/cargo-about.log" >&2
  exit 1
}
crates="$(awk '/^Used by:$/ {u=1; next} /^$/ {u=0} u && /^  / {print $1" "$2}' "$work/rust.txt" | sort -u | wc -l | tr -d ' ')"

(cd web && bun install --frozen-lockfile --silent && bun scripts/third-party-notices.ts) >"$work/web.txt"

{
  cat <<EOF
THIRD-PARTY NOTICES FOR APB

apb is licensed under the Apache License 2.0 (see LICENSE). The apb binary
also contains third-party software: Rust crates compiled into it and the npm
packages of the web dashboard it embeds. Their license terms and copyright
notices follow.

This file is generated by scripts/third-party-notices.sh from Cargo.lock and
web/bun.lock. Do not edit it by hand.

================================================================================
PART 1. RUST CRATES
================================================================================

The apb binary for the release targets (aarch64-apple-darwin,
x86_64-apple-darwin, x86_64-unknown-linux-gnu, x86_64-unknown-linux-musl)
includes ${crates} third-party crates. Where a crate offers a choice of
licenses, the license listed is the one apb uses it under.

EOF
  cat "$work/rust.txt"
  cat <<EOF

================================================================================
PART 2. WEB DASHBOARD (NPM PACKAGES)
================================================================================

EOF
  cat "$work/web.txt"
} | sed -e 's/[[:space:]]*$//' | cat -s >"$work/notices.txt"

# Never ship a local path (a cargo registry or node_modules location).
if grep -nE '/(home|Users)/|/\.cargo/registry|node_modules/' "$work/notices.txt" >&2; then
  echo "error: the generated notices contain a local path" >&2
  exit 1
fi

if [ "$mode" = "--check" ]; then
  if ! diff -u "$out" "$work/notices.txt" >"$work/diff.txt"; then
    head -n 60 "$work/diff.txt" >&2
    echo "error: THIRD-PARTY-NOTICES.txt is stale; run scripts/third-party-notices.sh and commit the result" >&2
    exit 1
  fi
  echo "THIRD-PARTY-NOTICES.txt is up to date"
else
  cp "$work/notices.txt" "$out"
  echo "wrote THIRD-PARTY-NOTICES.txt ($crates Rust crates)"
fi
