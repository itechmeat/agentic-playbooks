//! The repository's writing rule over every tracked file: no em dash
//! anywhere (docs, code, comments, strings, data), and no exclamation mark
//! in Markdown prose. Exclamation marks are checked only in Markdown, outside
//! fenced code blocks, inline code spans, HTML comments, link destinations
//! and autolinks, and only where one ends a word (`done!`, not `!=`, `!x`
//! or `![`). Everywhere else `!` is mostly syntax, so they stay unchecked:
//! in Rust, TypeScript, Svelte, YAML, JSON and shell files, doc comments
//! included. The `bundled/` folder keeps its own stricter lint
//! (`bundled_content_lint_test`).

use std::io::ErrorKind;
use std::path::{Path, PathBuf};
use std::process::Command;

/// How every failure of this file names the check.
const RULE: &str = "writing rule (CLAUDE.md, Conventions)";

/// Tracked files the rule does not cover, each by its exact path (never a
/// folder, so a new file is always checked): third-party text apb carries
/// as it is, and dated records kept as they were written.
const EXCLUDED: &[&str] = &[
    // The license texts of the dependencies, generated by
    // scripts/third-party-notices.sh.
    "THIRD-PARTY-NOTICES.txt",
    // NEAR AI Cloud's public catalog, embedded as the provider wrote it.
    "assets/cloud-models/near-ai-cloud.json",
    // A published release body.
    "docs/release-notes/v0.20.1.md",
    // Dated implementation plans.
    "docs/superpowers/plans/2026-07-12-agent-profiles-plan.md",
    "docs/superpowers/plans/2026-07-17-run-progress.md",
    "docs/superpowers/plans/2026-07-18-run-io-subplaybooks.md",
    "docs/superpowers/plans/2026-07-21-install-story.md",
    "docs/superpowers/plans/2026-07-30-buzz-apb-operator-pack.md",
    "docs/superpowers/plans/2026-08-06-followups-77-85.md",
    "docs/superpowers/plans/2026-08-15-atrip-connector.md",
    "docs/superpowers/plans/2026-08-15-playbook-interview.md",
    "docs/superpowers/plans/2026-08-15-qoder-agent-and-models-refresh.md",
    "docs/superpowers/plans/2026-08-16-server-mode.md",
    "docs/superpowers/plans/2026-08-16-twenty-connector.md",
    "docs/superpowers/plans/2026-08-16-webhook-ingest.md",
];

const EM_DASH: char = '\u{2014}';

/// What a blanked code span, comment or link destination reads as: a
/// letter, so an exclamation mark right after it is not taken for the
/// start of a word.
const BLANK: char = 'x';

fn repo_root() -> PathBuf {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    root.canonicalize().unwrap_or(root)
}

/// Why the tracked files were not listed.
enum Unlisted {
    /// No git, or no checkout of this tree (a build from a source
    /// archive): there is no list to check.
    NoCheckout(String),
    /// git ran on a checkout and failed.
    Failed(String),
}

/// The tracked files, as paths relative to the repository root. With no
/// git or no checkout to ask it prints one line that says the rule was not
/// checked and returns `None`, except in CI (`CI` set), where it fails, so
/// the check never drops out of a pipeline unseen. Any other failure fails
/// everywhere.
fn tracked_files(root: &Path) -> Option<Vec<String>> {
    match list_tracked(root) {
        Ok(files) => Some(files),
        Err(Unlisted::NoCheckout(why)) if std::env::var_os("CI").is_none() => {
            eprintln!("{RULE} not checked: {why}");
            None
        }
        Err(Unlisted::NoCheckout(why) | Unlisted::Failed(why)) => {
            panic!("{RULE} cannot be checked: {why}")
        }
    }
}

fn list_tracked(root: &Path) -> Result<Vec<String>, Unlisted> {
    let mut cmd = Command::new("git");
    // Every `GIT_*` variable is removed, `GIT_DIR`, `GIT_WORK_TREE` and
    // `GIT_INDEX_FILE` included: the test reads the checkout it was built
    // from, never one the caller's environment points at (a git hook that
    // runs the tests exports them for the hook's own repository).
    for (k, _) in std::env::vars_os() {
        if k.as_encoded_bytes().starts_with(b"GIT_") {
            cmd.env_remove(k);
        }
    }
    // A checkout another user owns (a workspace mounted into a container)
    // is read all the same.
    let out = cmd
        .args(["-c", "safe.directory=*", "-C"])
        .arg(root)
        .args(["ls-files", "-z"])
        .output()
        .map_err(|e| match e.kind() {
            ErrorKind::NotFound => Unlisted::NoCheckout(format!("git is not installed ({e})")),
            _ => Unlisted::Failed(format!("git did not start: {e}")),
        })?;
    if !out.status.success() {
        let why = format!(
            "git ls-files failed ({}): {}",
            out.status,
            String::from_utf8_lossy(&out.stderr).trim()
        );
        return Err(if in_checkout(root) {
            Unlisted::Failed(why)
        } else {
            Unlisted::NoCheckout(format!("{} is not a git checkout; {why}", root.display()))
        });
    }
    let listing = String::from_utf8(out.stdout)
        .map_err(|e| Unlisted::Failed(format!("tracked paths are not UTF-8: {e}")))?;
    let files: Vec<String> = listing
        .split('\0')
        .filter(|p| !p.is_empty())
        .map(str::to_string)
        .collect();
    if files.is_empty() {
        return Err(Unlisted::NoCheckout(format!(
            "the repository around {} tracks none of its files",
            root.display()
        )));
    }
    Ok(files)
}

/// Whether `root` or a folder above it holds the `.git` entry git looks
/// for. Without one, a failing `git ls-files` means a tree that is no
/// checkout (a source archive), not a broken checkout.
fn in_checkout(root: &Path) -> bool {
    root.ancestors().any(|dir| dir.join(".git").exists())
}

fn excluded(path: &str) -> bool {
    EXCLUDED.contains(&path)
}

/// `text` with every fenced code block, HTML comment, inline code span,
/// link destination and autolink replaced character by character (line
/// breaks kept, so line numbers hold): what is left is the prose.
///
/// It is a line scanner, not a Markdown parser, so it does not catch: a
/// word-final `!` followed by a character the rule does not list
/// (`done!?`, `done!</b>`); prose between two backslash-escaped backticks,
/// which it pairs as a code span; the rest of the file after a fence left
/// unclosed inside a list item (CommonMark ends that fence with the item);
/// and a `!` between `](` and the next `)` with no space between, which it
/// takes for a link destination wherever it stands. A link destination
/// with a space in it (a title) is not blanked, so a `!` there is reported.
fn markdown_prose(text: &str) -> Vec<char> {
    let mut chars: Vec<char> = text.chars().collect();
    blank_fences(&mut chars);
    blank_delimited(&mut chars, "<!--", "-->", true);
    blank_code_spans(&mut chars);
    blank_delimited(&mut chars, "](", ")", false);
    blank_delimited(&mut chars, "<http", ">", false);
    chars
}

fn blank(chars: &mut [char], from: usize, to: usize) {
    for c in &mut chars[from..to] {
        if *c != '\n' {
            *c = BLANK;
        }
    }
}

/// Blanks every line from a fence (three or more backticks or tildes) to
/// its closing fence, both included; an unclosed fence runs to the end.
/// As in CommonMark, a backtick fence opens only when the rest of its line
/// (the info string) holds no backtick, so a line that starts with a code
/// span of three backticks stays prose.
fn blank_fences(chars: &mut [char]) {
    let mut open: Option<(char, usize)> = None;
    let mut start = 0;
    while start < chars.len() {
        let end = chars[start..]
            .iter()
            .position(|c| *c == '\n')
            .map_or(chars.len(), |p| start + p);
        let line: String = chars[start..end].iter().collect();
        let trimmed = line.trim();
        let fence = |c: char| trimmed.chars().take_while(|x| *x == c).count();
        match open {
            Some((c, n)) => {
                if fence(c) >= n && trimmed.chars().all(|x| x == c) {
                    open = None;
                }
                blank(chars, start, end);
            }
            None => {
                for c in ['`', '~'] {
                    let n = fence(c);
                    let info_ok = c == '~' || !trimmed.chars().skip(n).any(|x| x == '`');
                    if n >= 3 && info_ok {
                        open = Some((c, n));
                        blank(chars, start, end);
                        break;
                    }
                }
            }
        }
        start = end + 1;
    }
}

fn starts_with(chars: &[char], at: usize, s: &str) -> bool {
    let n = s.chars().count();
    chars
        .get(at..at + n)
        .is_some_and(|w| w.iter().copied().eq(s.chars()))
}

/// Whether `chars[from..to]` crosses a blank line, which ends a paragraph
/// and so any inline construct.
fn crosses_paragraph(chars: &[char], from: usize, to: usize) -> bool {
    let mut newline = false;
    for c in &chars[from..to] {
        match c {
            '\n' if newline => return true,
            '\n' => newline = true,
            c if c.is_whitespace() => {}
            _ => newline = false,
        }
    }
    false
}

/// Blanks every `open ... close` (both included); with `multiline` it may
/// span paragraphs, else it ends at the line and never holds a space.
fn blank_delimited(chars: &mut [char], open: &str, close: &str, multiline: bool) {
    let close_chars: Vec<char> = close.chars().collect();
    let mut i = 0;
    while i < chars.len() {
        if !starts_with(chars, i, open) {
            i += 1;
            continue;
        }
        let from = i + open.chars().count();
        let mut j = from;
        let mut found = None;
        while j < chars.len() {
            if starts_with(chars, j, close) {
                found = Some(j + close_chars.len());
                break;
            }
            if !multiline && chars[j].is_whitespace() {
                break;
            }
            j += 1;
        }
        match found {
            Some(end) => {
                blank(chars, i, end);
                i = end;
            }
            None => i = from,
        }
    }
}

/// Blanks every inline code span: a run of backticks closed by the next
/// run of the same length within its paragraph. A run with no closer is
/// left as text.
fn blank_code_spans(chars: &mut [char]) {
    let run_at = |chars: &[char], i: usize| chars[i..].iter().take_while(|c| **c == '`').count();
    let mut i = 0;
    while i < chars.len() {
        if chars[i] != '`' {
            i += 1;
            continue;
        }
        let n = run_at(chars, i);
        let mut j = i + n;
        let mut closed = None;
        while j < chars.len() {
            if chars[j] == '`' {
                let m = run_at(chars, j);
                if m == n {
                    closed = Some(j + m);
                    break;
                }
                j += m;
            } else {
                j += 1;
            }
        }
        match closed {
            Some(end) if !crosses_paragraph(chars, i, end) => {
                blank(chars, i, end);
                i = end;
            }
            _ => i += n,
        }
    }
}

/// The lines of Markdown `text` whose prose holds an exclamation mark that
/// ends a word: after a character that is not a space, and before the end
/// of the line, a space, another `!` or closing punctuation.
fn prose_exclamations(text: &str) -> Vec<usize> {
    let prose: String = markdown_prose(text).into_iter().collect();
    let mut hits = Vec::new();
    for (n, line) in prose.lines().enumerate() {
        let chars: Vec<char> = line.chars().collect();
        let ends_word = chars.iter().enumerate().any(|(i, c)| {
            *c == '!'
                && i > 0
                && !chars[i - 1].is_whitespace()
                && chars[i - 1] != '!'
                && chars
                    .get(i + 1)
                    .is_none_or(|x| x.is_whitespace() || "!)\"'*_.,;:]".contains(*x))
        });
        if ends_word {
            hits.push(n + 1);
        }
    }
    hits
}

#[test]
fn tracked_files_hold_no_em_dash_and_markdown_prose_no_exclamation_mark() {
    let root = repo_root();
    let Some(files) = tracked_files(&root) else {
        return;
    };
    assert!(
        files.len() > 100,
        "{RULE}: only {} tracked files",
        files.len()
    );
    let mut problems = Vec::new();
    for rel in files.iter().filter(|f| !excluded(f)) {
        let path = root.join(rel);
        // A tracked file deleted in the working tree, a link or a
        // directory (a submodule) holds no text of its own.
        if !std::fs::symlink_metadata(&path).is_ok_and(|m| m.is_file()) {
            continue;
        }
        let bytes = std::fs::read(&path).unwrap_or_else(|e| panic!("read {rel}: {e}"));
        // Not UTF-8: an image, a font or another binary.
        let Ok(text) = String::from_utf8(bytes) else {
            continue;
        };
        for (n, line) in text.lines().enumerate() {
            if line.contains(EM_DASH) {
                problems.push(format!("{rel}:{}: em dash", n + 1));
            }
        }
        if rel.ends_with(".md") {
            for n in prose_exclamations(&text) {
                problems.push(format!("{rel}:{n}: exclamation mark in prose"));
            }
        }
    }
    assert!(problems.is_empty(), "{RULE}:\n{}", problems.join("\n"));
}

/// The exclusion list names only files that are still tracked, so it
/// cannot grow stale and hide a new file of the same name.
#[test]
fn every_exclusion_names_a_tracked_file() {
    let Some(files) = tracked_files(&repo_root()) else {
        return;
    };
    for e in EXCLUDED {
        assert!(
            files.iter().any(|f| f == e),
            "{RULE}: `{e}` is excluded but not tracked"
        );
    }
}

#[test]
fn markdown_prose_leaves_code_comments_and_links_out() {
    let text = "Done!\n\
        `a != b` and `x!` are code.\n\
        A span ``with ` inside!`` too.\n\
        ```a`b``` opens no fence, done!\n\
        ```\nlet x = y!;\n```\n\
        ~~~ a`b\nlet y = z!;\n~~~\n\
        <!-- a comment! -->\n\
        ![image](a!b.png) and [link](https://x.test/!) and <https://x.test/a!>\n\
        [link](https://x.test/) then done!)\n\
        Not equal: a != b, negated: !flag, macro: include_str!(x).\n\
        Wrapped `code\nacross lines!` still code.\n\
        Really (yes!) and **bold!** and twice!!\n";
    assert_eq!(prose_exclamations(text), vec![1, 4, 13, 17]);
}
