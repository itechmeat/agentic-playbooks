/// The `testing` features (test seams such as the stub MCP server) never
/// reach a shipped binary: every workspace crate that defines one refuses a
/// build without debug assertions, and no crate turns one on outside its
/// dev-dependencies (feature unification would otherwise compile the seam
/// into every build of `apb`, release included).
#[test]
fn testing_features_stay_in_test_builds() {
    let root = repo_root();
    let crates = root.join("crates");
    let mut manifests: Vec<PathBuf> = std::fs::read_dir(&crates)
        .expect("crates dir")
        .map(|e| e.expect("dir entry").path().join("Cargo.toml"))
        .filter(|p| p.is_file())
        .collect();
    manifests.sort();
    assert!(manifests.len() >= 7, "every workspace crate: {manifests:?}");
    let mut defining = 0;
    for manifest in &manifests {
        let text = std::fs::read_to_string(manifest).expect("read manifest");
        let mut section = String::new();
        for line in text.lines() {
            let trimmed = line.trim();
            if trimmed.starts_with('[') {
                section = trimmed.to_string();
                continue;
            }
            if trimmed.starts_with('#') {
                continue;
            }
            if section == "[features]" && trimmed.starts_with("testing") {
                defining += 1;
                let lib = manifest.parent().expect("crate dir").join("src/lib.rs");
                let lib = std::fs::read_to_string(&lib).expect("read lib.rs");
                assert!(
                    lib.contains(r#"#[cfg(all(feature = "testing", not(debug_assertions)))]"#)
                        && lib.contains("compile_error!"),
                    "{} defines a `testing` feature without the compile_error guard",
                    manifest.display()
                );
            }
            let takes_testing =
                trimmed.contains("path = \"../apb-") && trimmed.contains("\"testing\"");
            if takes_testing {
                assert!(
                    section.ends_with("dev-dependencies]"),
                    "{}: `{trimmed}` turns a testing feature on in `{section}`; only dev-dependencies may",
                    manifest.display()
                );
            }
        }
    }
    assert!(
        defining >= 4,
        "the crates that define a testing feature were found: {defining}"
    );
}

/// The aggregate check the main ruleset requires runs under `!cancelled()`,
/// so it also runs after a job it needs failed; it fails only on what its
/// step compares. Every job it needs therefore has its own variable and its
/// own comparison, the packaging job `crates` and the minimum Rust version
/// job `msrv` included.
#[cfg(unix)]
#[test]
fn the_required_check_fails_unless_every_linux_job_succeeded() {
    let doc = load(&repo_root().join(".github/workflows/ci.yml"));
    let job = doc
        .get("jobs")
        .and_then(|j| j.get("build-and-test"))
        .expect("the build-and-test job");
    let mut needed = needs(job);
    needed.sort();
    assert_eq!(
        needed,
        [
            "crates",
            "journal-corpus",
            "lint",
            "msrv",
            "test-linux",
            "web"
        ],
        "build-and-test needs every Linux job"
    );
    assert_eq!(condition(job), "${{ !cancelled() }}");
    let steps = Release::steps(job);
    assert_eq!(steps.len(), 1, "one comparing step");
    let env = steps[0]
        .get("env")
        .and_then(Value::as_mapping)
        .expect("the step env");
    let mut mapped: Vec<(String, String)> = env
        .iter()
        .map(|(k, v)| {
            let value = v.as_str().expect("env value");
            let job = value
                .strip_prefix("${{ needs.")
                .and_then(|s| s.strip_suffix(".result }}"))
                .unwrap_or_else(|| panic!("{value} maps a job result"));
            (job.to_string(), k.as_str().expect("env name").to_string())
        })
        .collect();
    mapped.sort();
    let jobs: Vec<&str> = mapped.iter().map(|(j, _)| j.as_str()).collect();
    assert_eq!(jobs, needed, "one variable per needed job and nothing else");

    let script = run_of(steps[0]);
    let run = |failing: Option<(&str, &str)>| -> bool {
        let mut cmd = std::process::Command::new("bash");
        cmd.arg("-c").arg(script);
        for (_, var) in &mapped {
            let value = match failing {
                Some((v, result)) if v == var => result,
                _ => "success",
            };
            cmd.env(var, value);
        }
        cmd.output().expect("run bash").status.success()
    };
    assert!(run(None), "every job succeeded");
    for (_, var) in &mapped {
        for result in ["failure", "cancelled", "skipped"] {
            assert!(
                !run(Some((var, result))),
                "{var}={result} fails the required check"
            );
        }
    }
}

