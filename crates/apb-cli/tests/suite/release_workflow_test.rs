#[test]
fn the_macos_pr_leg_runs_the_release_gates_clippy() {
    // cfg(target_os) code only compiles, and so only lints, on its own
    // platform: 1.0.0-beta.3's release gate failed on dead code only macOS
    // built, which no pull request had linted. The macOS leg of CI runs the
    // gate's clippy command, with the component installed, before its tests.
    fn run_of(s: &Value) -> &str {
        s.get("run").and_then(Value::as_str).unwrap_or_default()
    }
    fn clippy_of<'a>(steps: &[&'a Value], what: &str) -> (usize, &'a str) {
        steps
            .iter()
            .enumerate()
            .find(|(_, s)| run_of(s).contains("cargo clippy"))
            .map(|(i, s)| (i, run_of(s).trim()))
            .unwrap_or_else(|| panic!("{what} runs clippy"))
    }
    let gate = load(&repo_root().join(".github/workflows/test-gate.yml"));
    let gate_job = gate
        .get("jobs")
        .and_then(|j| j.get("gate"))
        .expect("test-gate.yml has a `gate` job");
    let gate_steps = Release::steps(gate_job);
    let (at, gate_clippy) = clippy_of(&gate_steps, "the release gate");
    assert!(
        gate_steps[at].get("if").is_none(),
        "the release gate lints on every leg"
    );
    let ci = load(&repo_root().join(".github/workflows/ci.yml"));
    let job = ci
        .get("jobs")
        .and_then(|j| j.get("test-macos"))
        .expect("ci.yml has a `test-macos` job");
    assert!(
        job.get("runs-on")
            .and_then(Value::as_str)
            .is_some_and(|r| r.starts_with("macos")),
        "test-macos runs on macOS"
    );
    let steps = Release::steps(job);
    let (clippy, command) = clippy_of(&steps, "test-macos");
    assert_eq!(command, gate_clippy, "the same clippy command as the gate");
    assert!(
        steps[clippy].get("if").is_none(),
        "test-macos lints unconditionally"
    );
    let toolchain = steps
        .iter()
        .position(|s| {
            s.get("uses")
                .and_then(Value::as_str)
                .is_some_and(|u| u.starts_with("dtolnay/rust-toolchain@"))
        })
        .expect("test-macos installs Rust");
    assert!(
        steps[toolchain]
            .get("with")
            .and_then(|w| w.get("components"))
            .and_then(Value::as_str)
            .is_some_and(|c| c.split(',').any(|c| c.trim() == "clippy")),
        "test-macos installs the clippy component"
    );
    assert!(toolchain < clippy, "Rust is installed before clippy runs");
    let test = steps
        .iter()
        .position(|s| run_of(s).contains("cargo nextest run"))
        .expect("test-macos runs nextest");
    assert!(clippy < test, "clippy runs before the tests");
}

fn assert_runs_the_sandbox_tests(job: &Value, required: &str) {
    let steps = Release::steps(job);
    fn run_of(s: &Value) -> &str {
        s.get("run").and_then(Value::as_str).unwrap_or_default()
    }
    let install = steps
        .iter()
        .position(|s| run_of(s).contains("apt-get install -y --no-install-recommends bubblewrap"))
        .expect("the Linux test leg installs bubblewrap");
    assert!(
        run_of(steps[install]).contains("apt-get update"),
        "the package index is refreshed before the install"
    );
    let test = steps
        .iter()
        .position(|s| run_of(s).contains("cargo nextest run"))
        .expect("the Linux test leg runs nextest");
    assert!(install < test, "bubblewrap is installed before the tests");
    assert_eq!(
        steps[test]
            .get("env")
            .and_then(|e| e.get("APB_SANDBOX_TESTS"))
            .and_then(Value::as_str),
        Some(required),
        "the Linux test step requires the sandbox tests to run"
    );
    assert!(
        !run_of(steps[test]).contains("sudo"),
        "the tests run as the normal user"
    );
}

// Release notes. dist runs post-announce jobs after the Homebrew publish,
// which is skipped on a pre-release, so the notes are applied by a separate
// `workflow_run` workflow instead. Its job condition and its first step
// decide whether a completed Release run may edit a release at all.

const NOTES_WORKFLOW: &str = ".github/workflows/release-notes.yml";

fn notes_job() -> (Value, Value) {
    let doc = load(&repo_root().join(NOTES_WORKFLOW));
    let jobs = doc
        .get("jobs")
        .and_then(Value::as_mapping)
        .expect("release-notes.yml jobs");
    assert_eq!(jobs.len(), 1, "release-notes.yml has exactly one job");
    let job = jobs.values().next().expect("one job").clone();
    (doc, job)
}

fn run_of(step: &Value) -> &str {
    step.get("run").and_then(Value::as_str).unwrap_or_default()
}

/// Evaluates the subset of GitHub's expression syntax the notes job uses:
/// `a == b` clauses joined by `&&`, each side a quoted literal or a
/// `github.` context path. Anything else fails the test rather than being
/// misread, so a new construct in the condition needs a matching evaluator.
fn eval_condition(cond: &str, github: &Value) -> bool {
    for banned in ["||", "!", "(", "${{"] {
        assert!(
            !cond.contains(banned),
            "unsupported construct {banned:?} in {cond}"
        );
    }
    let side = |s: &str| -> String {
        let s = s.trim();
        if let Some(lit) = s.strip_prefix('\'').and_then(|s| s.strip_suffix('\'')) {
            return lit.to_string();
        }
        let path = s
            .strip_prefix("github.")
            .unwrap_or_else(|| panic!("unsupported operand {s:?}"));
        path.split('.')
            .try_fold(github, |v, key| v.get(key))
            .and_then(Value::as_str)
            .unwrap_or_default()
            .to_string()
    };
    cond.split("&&").all(|clause| {
        let (lhs, rhs) = clause
            .split_once("==")
            .unwrap_or_else(|| panic!("unsupported clause {clause:?}"));
        side(lhs) == side(rhs)
    })
}

const REPO: &str = "itechmeat/agentic-playbooks";
const BUILT: &str = "0123456789abcdef0123456789abcdef01234567";

/// The `github` context of a completed Release run.
fn release_run(event: &str, conclusion: &str, head_repo: &str, branch: &str) -> Value {
    yaml_serde::from_str(&format!(
        "repository: {REPO}\n\
         event:\n  workflow_run:\n    event: {event}\n    conclusion: {conclusion}\n    \
         head_branch: '{branch}'\n    head_sha: {BUILT}\n    \
         head_repository:\n      full_name: {head_repo}\n"
    ))
    .expect("fixture")
}

#[test]
fn release_notes_follow_every_completed_release_run() {
    let root = repo_root();
    let (doc, job) = notes_job();

    // The trigger names the generated workflow by its `name`.
    let release_name = load(&root.join(".github/workflows/release.yml"))
        .get("name")
        .and_then(Value::as_str)
        .expect("release.yml name")
        .to_string();
    let trigger = doc
        .get("on")
        .and_then(|o| o.get("workflow_run"))
        .expect("release-notes.yml runs on workflow_run");
    let list = |key: &str| -> Vec<String> {
        trigger
            .get(key)
            .and_then(Value::as_sequence)
            .map(|s| {
                s.iter()
                    .filter_map(|v| v.as_str().map(str::to_string))
                    .collect()
            })
            .unwrap_or_default()
    };
    assert_eq!(list("workflows"), vec![release_name]);
    assert_eq!(list("types"), vec!["completed".to_string()]);
    assert_eq!(
        doc.get("on").and_then(Value::as_mapping).map(|m| m.len()),
        Some(1),
        "workflow_run is the only trigger"
    );

    // Nothing by default, contents: write on the one job only.
    assert!(
        doc.get("permissions")
            .and_then(Value::as_mapping)
            .is_some_and(|m| m.is_empty()),
        "top-level permissions must be {{}}"
    );
    let perms = job
        .get("permissions")
        .and_then(Value::as_mapping)
        .expect("job permissions");
    assert_eq!(perms.len(), 1, "the job asks for contents: write only");
    assert_eq!(
        job.get("permissions")
            .and_then(|p| p.get("contents"))
            .and_then(Value::as_str),
        Some("write")
    );

    // The condition: a successful push run of this repository.
    let cond = condition(&job);
    for clause in [
        "github.event.workflow_run.conclusion == 'success'",
        "github.event.workflow_run.event == 'push'",
        "github.event.workflow_run.head_repository.full_name == github.repository",
    ] {
        assert!(cond.contains(clause), "the job condition lacks {clause}");
    }
    let env = |key: &str| {
        job.get("env")
            .and_then(|e| e.get(key))
            .and_then(Value::as_str)
            .unwrap_or_default()
            .to_string()
    };
    assert_eq!(env("TAG"), "${{ github.event.workflow_run.head_branch }}");
    assert_eq!(env("HEAD_SHA"), "${{ github.event.workflow_run.head_sha }}");

    // The tag is verified before the checkout, the checkout takes the
    // verified commit without credentials, and the edit comes last.
    let steps = Release::steps(&job);
    let verify = steps
        .iter()
        .position(|s| run_of(s).contains("git/ref/tags/${TAG}"))
        .expect("a step looks up the tag ref");
    let checkout = steps
        .iter()
        .position(|s| {
            s.get("uses")
                .and_then(Value::as_str)
                .is_some_and(|u| u.starts_with("actions/checkout@"))
        })
        .expect("a checkout step");
    let with = |key: &str| steps[checkout].get("with").and_then(|w| w.get(key));
    assert_eq!(
        with("ref").and_then(Value::as_str),
        Some("${{ github.event.workflow_run.head_sha }}")
    );
    assert_eq!(
        with("persist-credentials").and_then(Value::as_bool),
        Some(false)
    );
    let edit = steps
        .iter()
        .position(|s| run_of(s).contains("gh release edit"))
        .expect("a step edits the release");
    assert!(
        verify < checkout && checkout < edit,
        "verify, then checkout, then edit"
    );
    // Nothing before the verification touches the repository or the release.
    assert!(
        steps[..verify].is_empty(),
        "the tag check is the first step"
    );

    // The generated release.yml no longer calls it, and dist has no
    // post-announce job that would bring the call back.
    let mut uses = Vec::new();
    collect_uses(
        &load(&root.join(".github/workflows/release.yml")),
        &mut uses,
    );
    assert!(
        !uses.iter().any(|u| u.contains("release-notes.yml")),
        "release.yml must not call release-notes.yml"
    );
    let dist = std::fs::read_to_string(root.join("dist-workspace.toml")).expect("dist config");
    assert!(
        !dist
            .lines()
            .any(|l| l.trim_start().starts_with("post-announce-jobs")),
        "post-announce jobs are skipped on pre-releases; keep them out"
    );
}

#[test]
fn the_notes_job_condition_admits_a_pre_release_and_refuses_a_pull_request() {
    let cond = condition(&notes_job().1);

    // A successful tag push of a pre-release runs the job.
    let pre = release_run("push", "success", REPO, "v1.0.0-beta.3");
    assert!(eval_condition(&cond, &pre), "a pre-release tag run passes");

    // A successful pull request run on a branch named like a tag does not.
    let pr = release_run("pull_request", "success", REPO, "v1.0.0");
    assert!(!eval_condition(&cond, &pr), "a pull request run is refused");

    // Nor does a failed tag run, or a run from another repository.
    let failed = release_run("push", "failure", REPO, "v1.0.0");
    assert!(!eval_condition(&cond, &failed), "a failed run is refused");
    let fork = release_run("push", "success", "someone/fork", "v1.0.0");
    assert!(!eval_condition(&cond, &fork), "a fork's run is refused");
}

/// The `run` script of the notes job's step that contains `marker`.
fn notes_step(marker: &str) -> String {
    let (_, job) = notes_job();
    Release::steps(&job)
        .iter()
        .map(|s| run_of(s))
        .find(|r| r.contains(marker))
        .unwrap_or_else(|| panic!("a notes step with {marker}"))
        .to_string()
}

/// Runs `script` with bash in `cwd`, with `gh` on the PATH as the stub
/// shell script `gh_stub` and the job's environment for `tag`.
#[cfg(unix)]
fn run_with_gh(
    script: &str,
    gh_stub: &str,
    cwd: &std::path::Path,
    tag: &str,
    head_sha: &str,
) -> std::process::Output {
    use std::os::unix::fs::PermissionsExt;

    let bin = tempfile::tempdir().expect("tempdir");
    let gh = bin.path().join("gh");
    std::fs::write(&gh, gh_stub).expect("write stub");
    std::fs::set_permissions(&gh, std::fs::Permissions::from_mode(0o755)).expect("chmod");
    let path = format!(
        "{}:{}",
        bin.path().display(),
        std::env::var("PATH").unwrap_or_default()
    );
    std::process::Command::new("bash")
        .arg("-c")
        .arg(script)
        .current_dir(cwd)
        .env("PATH", path)
        .env("GITHUB_REPOSITORY", REPO)
        .env("TAG", tag)
        .env("HEAD_SHA", head_sha)
        .output()
        .expect("run bash")
}

/// Runs the notes job's tag check with a stub `gh` that knows one annotated
/// tag, `v1.0.0-beta.3`, pointing (through a tag object) at `BUILT`.
#[cfg(unix)]
fn tag_check(tag: &str, head_sha: &str) -> std::process::Output {
    let stub = format!(
        "#!/bin/sh\n\
         case \"$2\" in\n\
         repos/{REPO}/git/ref/tags/v1.0.0-beta.3) echo 'tag 1111111111111111111111111111111111111111' ;;\n\
         repos/{REPO}/git/tags/1111111111111111111111111111111111111111) echo 'commit {BUILT}' ;;\n\
         *) echo 'gh: Not Found (HTTP 404)' >&2; exit 1 ;;\n\
         esac\n"
    );
    let cwd = tempfile::tempdir().expect("tempdir");
    run_with_gh(
        &notes_step("git/ref/tags/${TAG}"),
        &stub,
        cwd.path(),
        tag,
        head_sha,
    )
}

/// The edit step needs the tag's notes file, and hands it to `gh release
/// edit` for this repository.
#[cfg(unix)]
#[test]
fn the_edit_step_requires_the_notes_file_and_edits_this_repositorys_release() {
    let tag = "v1.0.0-beta.3";
    let script = notes_step("gh release edit");
    let checkout = tempfile::tempdir().expect("tempdir");
    let calls = checkout.path().join("gh-calls");
    let stub = format!("#!/bin/sh\nprintf '%s\\n' \"$@\" > '{}'\n", calls.display());

    let missing = run_with_gh(&script, &stub, checkout.path(), tag, BUILT);
    assert!(
        !missing.status.success(),
        "a missing notes file fails the step"
    );
    assert!(!calls.exists(), "nothing is edited without notes");

    let notes = checkout.path().join("docs/release-notes");
    std::fs::create_dir_all(&notes).expect("notes dir");
    std::fs::write(notes.join(format!("{tag}.md")), "notes\n").expect("notes");
    let ok = run_with_gh(&script, &stub, checkout.path(), tag, BUILT);
    assert!(
        ok.status.success(),
        "{}",
        String::from_utf8_lossy(&ok.stderr)
    );
    let args: Vec<String> = std::fs::read_to_string(&calls)
        .expect("gh was called")
        .lines()
        .map(str::to_string)
        .collect();
    assert_eq!(
        args,
        [
            "release",
            "edit",
            tag,
            "--repo",
            REPO,
            "--notes-file",
            &format!("docs/release-notes/{tag}.md"),
        ]
    );
}

#[cfg(unix)]
#[test]
fn the_tag_check_accepts_only_a_version_tag_that_names_the_built_commit() {
    let ok = tag_check("v1.0.0-beta.3", BUILT);
    assert!(
        ok.status.success(),
        "a pre-release tag dereferenced to the built commit passes: {}",
        String::from_utf8_lossy(&ok.stderr)
    );
    // A branch named like a version has no tag ref.
    assert!(!tag_check("v1.0.0", BUILT).status.success());
    // The tag names another commit than the run built.
    let other = "fedcba9876543210fedcba9876543210fedcba98";
    assert!(!tag_check("v1.0.0-beta.3", other).status.success());
    // Not a version tag at all, checked before any lookup.
    for bad in ["main", "v1.0", "v1.0.0-beta 3", "v1.0.0;true"] {
        assert!(!tag_check(bad, BUILT).status.success(), "{bad} is refused");
    }
}
